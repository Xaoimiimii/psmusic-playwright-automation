// Writes src/data/test-metadata.ts from test-management/state/plan.json and issue-map.json: per scenario ID
// (TS-AREA-nn) its objective, preconditions, rule, functional area (Epic), user stories, acceptance criteria, risks
// and priority, plus the recorded bugs by acceptance-criterion reference. The reporting fixture reads it to give each
// Allure result its Epic / Feature / Story, severity, description and Jira links (docs/reporting.md §3).
// Run after every /plan-jira-xray or /sync-jira-xray: node scripts/test-management/export-test-metadata.mjs [--check]
//   --check  exit 1 if the committed file differs from what the plan produces (for CI or review).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../..');
const plan = JSON.parse(fs.readFileSync(path.join(root, 'test-management/state/plan.json'), 'utf8'));
const map = JSON.parse(fs.readFileSync(path.join(root, 'test-management/state/issue-map.json'), 'utf8'));
const outFile = path.join(root, 'src/data/test-metadata.ts');

const byLocalId = new Map(plan.entities.map((e) => [e.localId, e]));
const byId = (a, b) => a.localeCompare(b, 'en', { numeric: true });

/** Jira key of a planned entity, only once it exists in Jira (same rule as export-test-keys.mjs). */
function jiraKey(localId) {
  const entry = map.entities[localId];
  return entry?.jiraKey && ['created', 'matched', 'updated'].includes(entry.creationStatus) ? entry.jiraKey : undefined;
}

function field(description, name) {
  return description.match(new RegExp(`\\*\\*${name}:\\*\\*\\s*([^\\n|]+)`))?.[1].trim();
}

function related(from, relationshipKey) {
  return plan.relationships.filter((r) => r.from === from && r.relationshipKey === relationshipKey).map((r) => r.to);
}

/** "US-002 Log in" -> "Log in": the summary without its leading local ID. */
function nameOf(entity) {
  return entity.summary.replace(new RegExp(`^${entity.localId}\\s+`), '');
}

/** Acceptance criteria text by ID ("US-002-AC-03" -> "Valid credentials: ..."), read from each story's "- AC-nn:" lines. */
const acText = new Map();
for (const story of plan.entities.filter((e) => e.type === 'story')) {
  for (const match of story.description.matchAll(/^- (AC-\d+):\s*(.+)$/gm)) {
    acText.set(`${story.localId}-${match[1]}`, match[2].trim());
  }
}

function ref(localId) {
  const entity = byLocalId.get(localId);
  return entity ? { id: localId, name: nameOf(entity), jiraKey: jiraKey(localId) } : { id: localId, name: localId };
}

const scenarios = {};
for (const test of plan.entities.filter((e) => e.type === 'test').sort((a, b) => byId(a.localId, b.localId))) {
  const stories = related(test.localId, 'testCoversRequirement').sort(byId);
  // A story's parent is its functional area (Epic). TECH has no parent (plan ambiguity AMB-TECH-NO-EPIC): it is its own group.
  const epicIds = [...new Set(stories.map((id) => related(id, 'storyParent')[0] ?? id))].sort(byId);
  const acIds = (field(test.description, 'Story / AC') ?? '').split(/,\s*/).filter((id) => /^US-\d+-AC-\d+$/.test(id));
  scenarios[test.localId] = {
    title: nameOf(test),
    objective: field(test.description, 'Objective'),
    preconditions: field(test.description, 'Preconditions'),
    rule: field(test.description, 'Rule'),
    priority: test.priority,
    epics: epicIds.map(ref),
    stories: stories.map(ref),
    acceptanceCriteria: acIds.map((id) => ({ id, text: acText.get(id) })),
    risks: related(test.localId, 'testCoversRisk').sort(byId).map((id) => ({ ...ref(id), priority: byLocalId.get(id)?.priority ?? undefined })),
    source: test.source,
  };
}

/** Recorded bugs by the reference knownDefect() is called with: "BUG-US-004-AC-01" is found under "US-004-AC-01". */
const bugs = {};
for (const bug of plan.entities.filter((e) => e.type === 'bug').sort((a, b) => byId(a.localId, b.localId))) {
  bugs[bug.localId.replace(/^BUG-/, '')] = { id: bug.localId, name: nameOf(bug), jiraKey: jiraKey(bug.localId) };
}

// JSON.stringify drops undefined fields, so absent values simply do not appear.
const text = `// GENERATED by scripts/test-management/export-test-metadata.mjs from test-management/state/plan.json and issue-map.json.
// Do not edit by hand: re-run the script after /plan-jira-xray or /sync-jira-xray.

export interface TraceRef {
  /** Local ID in the plan, e.g. "US-002", "PR-07", "FA-02". */
  id: string;
  name: string;
  /** Jira issue key in project ${map.projectKey}, once the entity exists in Jira. */
  jiraKey?: string;
}

export interface ScenarioMetadata {
  title: string;
  objective?: string;
  preconditions?: string;
  rule?: string;
  /** Risk-based scenario priority (docs/test-strategy/test-scenarios.md): High = P1, Medium = P2, Low = P3. */
  priority: 'High' | 'Medium' | 'Low' | null;
  /** Functional areas (Jira Epics); TECH stands for itself. */
  epics: TraceRef[];
  stories: TraceRef[];
  acceptanceCriteria: { id: string; text?: string }[];
  risks: (TraceRef & { priority?: string })[];
  source: string;
}

/** Scenario ID (docs/test-strategy/test-scenarios.md) -> traceability and intent of the scenario. */
export const scenarioMetadata: Readonly<Record<string, ScenarioMetadata>> = ${JSON.stringify(scenarios, null, 2)};

/** Acceptance-criterion reference (as passed to knownDefect) -> recorded bug. */
export const recordedBugs: Readonly<Record<string, TraceRef>> = ${JSON.stringify(bugs, null, 2)};
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.error(`${path.relative(root, outFile)} is out of date: run node scripts/test-management/export-test-metadata.mjs`);
    process.exit(1);
  }
  console.log(`${path.relative(root, outFile)} is up to date (${Object.keys(scenarios).length} scenarios)`);
} else {
  fs.writeFileSync(outFile, text);
  console.log(`wrote ${path.relative(root, outFile)} (${Object.keys(scenarios).length} scenarios, ${Object.keys(bugs).length} bugs)`);
}
