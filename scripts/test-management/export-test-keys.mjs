// Writes src/data/xray-test-keys.ts from test-management/state/issue-map.json: scenario ID (TS-AREA-nn) -> Xray Test
// key. The test fixture reads it to annotate each Playwright test with `test_key`, so JUnit results imported into
// Xray attach to the existing Tests instead of creating new Generic ones (docs/integrations/xray-cloud-rest-api.md §6).
// Run after every /sync-jira-xray that creates Tests: node scripts/test-management/export-test-keys.mjs [--check]
//   --check  exit 1 if the committed file differs from what the map produces (for CI or review).
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../..');
const map = JSON.parse(fs.readFileSync(path.join(root, 'test-management/state/issue-map.json'), 'utf8'));
const outFile = path.join(root, 'src/data/xray-test-keys.ts');

const byId = (a, b) => a.localeCompare(b, 'en', { numeric: true });
const rows = Object.values(map.entities)
  .filter((e) => e.type === 'test' && e.jiraKey && ['created', 'matched', 'updated'].includes(e.creationStatus))
  .sort((a, b) => byId(a.localId, b.localId))
  .map((e) => `  '${e.localId}': '${e.jiraKey}',`);

const text = `// GENERATED by scripts/test-management/export-test-keys.mjs from test-management/state/issue-map.json.
// Do not edit by hand: re-run the script after /sync-jira-xray.

/** Scenario ID (docs/test-strategy/test-scenarios.md) -> Xray Test key in Jira project ${map.projectKey}. */
export const xrayTestKeys: Readonly<Record<string, string>> = {
${rows.join('\n')}
};
`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.error(`${path.relative(root, outFile)} is out of date: run node scripts/test-management/export-test-keys.mjs`);
    process.exit(1);
  }
  console.log(`${path.relative(root, outFile)} is up to date (${rows.length} keys)`);
} else {
  fs.writeFileSync(outFile, text);
  console.log(`wrote ${path.relative(root, outFile)} (${rows.length} keys)`);
}
